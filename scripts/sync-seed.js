/**
 * Regenerates js/seed-data.js from data/*.json.
 *
 * seed-data.js lets the pages show populated data when they are opened straight
 * from the file system (file://) or through Live Server, where no API exists.
 * Run `npm run sync-seed` after editing the seed JSON files.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const resources = ['workers', 'bookings', 'ledger', 'feedback'];
const seed = {};
resources.forEach((r) => { seed[r] = JSON.parse(fs.readFileSync(path.join(root, 'data', r + '.json'), 'utf8')); });

const out = '/* AUTO-GENERATED by scripts/sync-seed.js from data/*.json — do not edit by hand. */\n' +
  'window.SEVAKHATA_SEED = ' + JSON.stringify(seed, null, 2) + ';\n';
fs.writeFileSync(path.join(root, 'js', 'seed-data.js'), out);
console.log('js/seed-data.js written (' + resources.map((r) => r + ':' + seed[r].length).join(', ') + ')');
